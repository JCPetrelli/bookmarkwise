"""Write the one-off extension for one approved plan."""

from __future__ import annotations

import json
import shutil
from pathlib import Path

from . import plan as plan_mod

TEMPLATE = Path(__file__).parent / "extension_template"


def build(plan: dict, out_dir: str | Path, force: bool = False) -> Path:
    plan_mod.assert_buildable(plan)
    out = Path(out_dir).expanduser()
    if out.exists():
        if not force:
            raise plan_mod.PlanError(f"{out} already exists: pick a new folder (or pass --force to replace it)")
        if not (out / "manifest.json").is_file() or "Bookmarkwise" not in (out / "manifest.json").read_text():
            raise plan_mod.PlanError(f"{out} exists and is not a Bookmarkwise extension folder: not replacing it")
        shutil.rmtree(out)
    shutil.copytree(TEMPLATE, out)

    manifest = json.loads((out / "manifest.json").read_text())
    manifest["name"] = f"Bookmarkwise apply {plan['hash'][:8]}"
    (out / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")

    payload = {k: plan[k] for k in ("title", "created", "hash", "counts", "ops")}
    (out / "plan.js").write_text(
        "// Generated by bookmarkwise build. One approved plan; do not edit by hand.\n"
        f"const PLAN = {json.dumps(payload, indent=1, ensure_ascii=False)};\n",
        encoding="utf-8",
    )
    return out
